-- Schema inicial do Booklit, igual ao que o Hibernate (ddl-auto) criava a partir das entidades.
--
-- Banco vazio (dev, Floci, um RDS novo): o Flyway roda este arquivo e depois os seguintes.
-- Banco que já existia antes do Flyway (produção): o baseline-on-migrate com baseline-version=1
-- marca este arquivo como aplicado sem rodá-lo, e só as versões seguintes são executadas.
--
-- Os nomes das constraints são os que o Hibernate gera (hash do nome da tabela e das colunas).
-- Em produção alguns podem ser outros (ver db/historico/README.md): migrações que mexam numa
-- constraint existente devem usar IF EXISTS em vez de confiar nestes nomes.
-- O histórico dos scripts aplicados à mão antes do Flyway está em db/historico/.

create table t_clube (
    privado boolean not null,
    created_at timestamp(6),
    codigo_convite varchar(16),
    id uuid not null,
    descricao varchar(255),
    nome varchar(255),
    status varchar(255) check (status in ('ATIVO','ENCERRADO')),
    primary key (id)
);

create table t_clube_tema (
    clube_id uuid not null,
    tema_id uuid not null
);

create table t_comentario (
    removido boolean not null,
    usuario_id integer,
    created_at timestamp(6),
    updated_at timestamp(6),
    comentario_pai_id uuid,
    id uuid not null,
    leitura_clube_id uuid,
    conteudo varchar(255),
    primary key (id)
);

create table t_convite (
    convidado_por integer,
    created_at timestamp(6),
    expira_em timestamp(6),
    clube_id uuid,
    id uuid not null,
    email_destinatario varchar(255),
    status varchar(255) check (status in ('PENDENTE','ACEITO','RECUSADO','EXPIRADO')),
    primary key (id)
);

create table t_desafio_otp (
    tentativas_restantes integer not null,
    consumido_em timestamp(6) with time zone,
    criado_em timestamp(6) with time zone not null,
    expira_em timestamp(6) with time zone not null,
    id uuid not null,
    finalidade varchar(30) not null check (finalidade in ('LOGIN','VERIFICAR_EMAIL','REDEFINIR_PIN')),
    codigo_hash varchar(64) not null,
    destinatario varchar(254) not null,
    primary key (id)
);

create table t_evento_processado (
    processado_em timestamp(6) with time zone not null,
    id uuid not null,
    tipo varchar(255) not null,
    primary key (id)
);

create table t_leitura_clube (
    valor_meta integer,
    data_fim timestamp(6),
    data_inicio timestamp(6),
    clube_id uuid,
    id uuid not null,
    livro_capa_url varchar(255),
    livro_google_id varchar(255),
    livro_titulo varchar(255),
    spotify_url varchar(255),
    tipo_meta varchar(255) check (tipo_meta in ('PAGINA','CAPITULO')),
    primary key (id)
);

create table t_leitura_pessoal (
    data_fim date,
    data_inicio date,
    nota integer,
    pagina_atual integer,
    total_paginas integer,
    usuario_id integer not null,
    created_at timestamp(6),
    updated_at timestamp(6),
    clube_origem_id uuid,
    id uuid not null,
    livro_autor varchar(255),
    livro_capa_url varchar(255),
    livro_google_id varchar(255) not null,
    livro_titulo varchar(255) not null,
    resenha TEXT,
    status varchar(255) not null check (status in ('QUERO_LER','LENDO','LIDO','ABANDONADO')),
    primary key (id),
    constraint uk_leitura_pessoal_usuario_livro unique (usuario_id, livro_google_id)
);

create table t_meta_leitura (
    ano integer not null,
    quantidade_livros integer not null,
    usuario_id integer not null,
    id uuid not null,
    primary key (id),
    constraint uk_meta_leitura_usuario_ano unique (usuario_id, ano)
);

create table t_opcao_voto (
    sugerido_por integer,
    id uuid not null,
    votacao_id uuid,
    livro_capa_url varchar(255),
    livro_google_id varchar(255),
    livro_titulo varchar(255),
    primary key (id)
);

create table t_outbox_evento (
    criado_em timestamp(6) with time zone not null,
    publicado_em timestamp(6) with time zone,
    agregado_id uuid not null,
    id uuid not null,
    payload text not null,
    tipo varchar(255) not null,
    primary key (id)
);

create table t_reacao (
    usuario_id integer not null,
    created_at timestamp(6),
    clube_id uuid not null,
    id uuid not null,
    alvo_id varchar(80) not null,
    tipo varchar(255) not null check (tipo in ('CURTIR','FOGO','PALMAS')),
    primary key (id),
    constraint uk_reacao_alvo_usuario unique (alvo_id, usuario_id)
);

create table t_registro (
    usuario_id integer,
    valor_atual integer,
    updated_at timestamp(6),
    id uuid not null,
    leitura_clube_id uuid,
    primary key (id)
);

create table t_tema (
    id uuid not null,
    nome varchar(255),
    primary key (id)
);

create table t_usuario (
    id integer generated by default as identity,
    created_at timestamp(6),
    email_verificado_em timestamp(6),
    bio varchar(160),
    foto_chave varchar(200),
    email varchar(255),
    nome varchar(255),
    senha_hash varchar(255),
    primary key (id)
);

create table t_usuario_clube (
    usuario_id integer,
    entrou_em timestamp(6),
    clube_id uuid,
    id uuid not null,
    papel varchar(255) check (papel in ('LIDER','MEMBRO')),
    primary key (id),
    constraint uk_usuario_clube unique (usuario_id, clube_id)
);

create table t_votacao (
    data_abertura timestamp(6),
    data_encerramento timestamp(6),
    clube_id uuid,
    id uuid not null,
    status varchar(255) check (status in ('ABERTA','ENCERRADA')),
    primary key (id)
);

create table t_voto (
    peso integer not null,
    usuario_id integer,
    id uuid not null,
    opcao_voto_id uuid,
    votacao_id uuid,
    primary key (id)
);

